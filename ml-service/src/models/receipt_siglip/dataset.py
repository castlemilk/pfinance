"""Dataset and training utilities for SigLIP receipt heads.

Silver labels: generated by running Qwen2-VL on receipt images and using
its structured output as ground truth for training the lightweight heads.
"""

import json
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

import torch
from PIL import Image
from torch.utils.data import Dataset

from .merchants import merchant_to_label

logger = logging.getLogger(__name__)


@dataclass
class ReceiptLabel:
    """Ground truth label for a receipt image."""
    merchant: str
    amount: float
    date_day: int
    date_month: int
    date_year: int
    line_item_count: int
    source: str  # "qwen2vl", "gemini", "human"
    confidence: float  # source model confidence


class ReceiptDataset(Dataset):
    """Dataset for training SigLIP receipt heads from silver/gold labels.

    Expected directory structure:
        data_dir/
            images/
                receipt_001.jpg
                receipt_002.png
                ...
            labels.jsonl   # one JSON object per line

    Label format (JSONL):
        {"image": "receipt_001.jpg", "merchant": "Woolworths", "amount": 45.50,
         "date": "2026-01-15", "line_item_count": 5, "source": "qwen2vl",
         "confidence": 0.92}
    """

    def __init__(
        self,
        data_dir: str,
        encoder=None,
        min_confidence: float = 0.7,
        transform=None,
    ):
        """Initialize dataset.

        Args:
            data_dir: Path to dataset directory.
            encoder: Optional SigLIPEncoder for on-the-fly preprocessing.
            min_confidence: Minimum source confidence to include a sample.
            transform: Optional PIL image transform.
        """
        self.data_dir = Path(data_dir)
        self.images_dir = self.data_dir / "images"
        self.encoder = encoder
        self.transform = transform

        # Load and filter labels
        labels_path = self.data_dir / "labels.jsonl"
        self.samples: list[tuple[str, ReceiptLabel]] = []

        if not labels_path.exists():
            logger.warning("No labels.jsonl found at %s", labels_path)
            return

        with open(labels_path) as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                obj = json.loads(line)

                # Filter low-confidence silver labels
                conf = obj.get("confidence", 0.0)
                if conf < min_confidence:
                    continue

                # Parse date
                date_parts = obj["date"].split("-")
                if len(date_parts) != 3:
                    continue

                label = ReceiptLabel(
                    merchant=obj["merchant"],
                    amount=float(obj["amount"]),
                    date_year=int(date_parts[0]),
                    date_month=int(date_parts[1]),
                    date_day=int(date_parts[2]),
                    line_item_count=obj.get("line_item_count", 0),
                    source=obj.get("source", "qwen2vl"),
                    confidence=conf,
                )

                image_file = obj["image"]
                image_path = self.images_dir / image_file
                if image_path.exists():
                    self.samples.append((image_file, label))

        logger.info(
            "Loaded %d samples from %s (filtered at confidence >= %.2f)",
            len(self.samples),
            data_dir,
            min_confidence,
        )

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> dict:
        """Get a single training sample.

        Returns dict with:
            - pixel_values: [3, 384, 384] preprocessed image tensor
            - merchant_label: int class index
            - amount_label: float
            - date_day: float
            - date_month: float
            - date_year: float
            - has_line_items: float (0 or 1)
            - sample_weight: float (source confidence as sample weight)
        """
        image_file, label = self.samples[idx]
        image_path = self.images_dir / image_file

        image = Image.open(image_path).convert("RGB")
        if self.transform:
            image = self.transform(image)

        # Preprocess with encoder's processor
        if self.encoder and self.encoder.is_loaded:
            pixel_values = self.encoder.preprocess(image).squeeze(0)
        else:
            # Fallback: basic resize + normalize
            from torchvision import transforms
            basic_transform = transforms.Compose([
                transforms.Resize((384, 384)),
                transforms.ToTensor(),
                transforms.Normalize(
                    mean=[0.485, 0.456, 0.406],
                    std=[0.229, 0.224, 0.225],
                ),
            ])
            pixel_values = basic_transform(image)

        return {
            "pixel_values": pixel_values,
            "merchant_label": merchant_to_label(label.merchant),
            "amount_label": label.amount,
            "date_day": float(label.date_day),
            "date_month": float(label.date_month),
            "date_year": float(label.date_year),
            "has_line_items": float(label.line_item_count > 0),
            "sample_weight": label.confidence,
        }


class SilverLabelGenerator:
    """Generate silver training labels by running Qwen2-VL on receipt images.

    This creates the training data for the SigLIP heads by using the existing
    Qwen2-VL pipeline as a teacher model.
    """

    def __init__(self, output_dir: str):
        self.output_dir = Path(output_dir)
        self.images_dir = self.output_dir / "images"
        self.images_dir.mkdir(parents=True, exist_ok=True)
        self.labels_path = self.output_dir / "labels.jsonl"

    def add_label(
        self,
        image: Image.Image,
        image_name: str,
        merchant: str,
        amount: float,
        date: str,
        line_item_count: int = 0,
        source: str = "qwen2vl",
        confidence: float = 0.0,
    ) -> None:
        """Add a labeled receipt to the training dataset.

        Args:
            image: PIL Image of the receipt.
            image_name: Filename for the image (e.g., "receipt_001.jpg").
            merchant: Extracted merchant name.
            amount: Extracted total amount.
            date: Extracted date as "YYYY-MM-DD".
            line_item_count: Number of line items detected.
            source: Which model produced this label.
            confidence: Source model's confidence score.
        """
        # Save image
        image_path = self.images_dir / image_name
        image.save(image_path)

        # Append label
        label = {
            "image": image_name,
            "merchant": merchant,
            "amount": amount,
            "date": date,
            "line_item_count": line_item_count,
            "source": source,
            "confidence": confidence,
        }

        with open(self.labels_path, "a") as f:
            f.write(json.dumps(label) + "\n")

    def get_stats(self) -> dict:
        """Get dataset statistics."""
        if not self.labels_path.exists():
            return {"total": 0}

        total = 0
        by_source: dict[str, int] = {}
        by_merchant: dict[str, int] = {}

        with open(self.labels_path) as f:
            for line in f:
                if not line.strip():
                    continue
                obj = json.loads(line)
                total += 1
                source = obj.get("source", "unknown")
                by_source[source] = by_source.get(source, 0) + 1
                merchant = obj.get("merchant", "unknown")
                by_merchant[merchant] = by_merchant.get(merchant, 0) + 1

        return {
            "total": total,
            "by_source": by_source,
            "top_merchants": dict(
                sorted(by_merchant.items(), key=lambda x: -x[1])[:20]
            ),
        }
